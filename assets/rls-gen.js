/* Supabase RLS policy generator — pure logic, no DOM.
 * Used by /supabase-rls-policy-generator/ and by the tests that run every
 * generated migration against Postgres as anon / authenticated users.
 * Exposes RLSGen.generate(opts) -> { sql, test, errors }.
 */
(function (root) {
  'use strict'

  var IDENT = /^[a-z_][a-z0-9_]{0,62}$/
  var OPS = ['select', 'insert', 'update', 'delete']

  var PATTERNS = {
    owner: 'Private: each user sees and changes only their own rows',
    owner_public_read: 'Public read, owner writes (profiles, posts, listings)',
    team: 'Team / workspace: members see and change their team’s rows',
    public_read_only: 'Public read-only (catalog, pricing): no writes from the API',
  }

  function q(name) { return name } // identifiers are validated, never quoted

  function generate(o) {
    o = o || {}
    var errors = []
    var schema = o.schema || 'public'
    var table = o.table || ''
    var pattern = o.pattern || 'owner'
    var ownerCol = o.ownerCol || 'user_id'
    var teamCol = o.teamCol || 'team_id'
    var membersTable = o.membersTable || 'team_members'
    var membersUserCol = o.membersUserCol || 'user_id'
    var membersTeamCol = o.membersTeamCol || 'team_id'
    var ops = (o.ops && o.ops.length ? o.ops : OPS).filter(function (x) { return OPS.indexOf(x) >= 0 })

    var check = { schema: schema, table: table }
    if (pattern === 'owner' || pattern === 'owner_public_read') check.ownerCol = ownerCol
    if (pattern === 'team') {
      check.teamCol = teamCol; check.membersTable = membersTable
      check.membersUserCol = membersUserCol; check.membersTeamCol = membersTeamCol
    }
    Object.keys(check).forEach(function (k) {
      if (!IDENT.test(check[k])) errors.push(k + ': use lowercase letters, digits and _ (start with a letter or _)')
    })
    if (!PATTERNS[pattern]) errors.push('pattern: unknown')
    if (schema === 'auth' || schema === 'storage' || schema === 'private') errors.push('schema: pick the schema your API exposes (usually public)')
    if (errors.length) return { sql: '', test: '', errors: errors }

    var t = schema + '.' + table
    var uid = '(select auth.uid())'
    var L = []
    var grants = { anon: [], authenticated: [] }
    function pol(name, op, role, using, withCheck) {
      var s = 'create policy "' + name + '" on ' + t + '\n  for ' + op + ' to ' + role
      if (using) s += '\n  using (' + using + ')'
      if (withCheck) s += '\n  with check (' + withCheck + ')'
      L.push(s + ';')
      L.push('')
    }
    function grant(role, op) { if (grants[role].indexOf(op) < 0) grants[role].push(op) }

    L.push('-- RLS for ' + t + ' · ' + PATTERNS[pattern])
    L.push('-- Generated by https://shipsealed.com/supabase-rls-policy-generator/')
    L.push('-- Run in the same migration that creates the table.')
    L.push('')
    L.push('alter table ' + t + ' enable row level security;')
    L.push('')

    if (pattern === 'owner' || pattern === 'owner_public_read') {
      var mine = ownerCol + ' = ' + uid
      if (pattern === 'owner_public_read') {
        pol('anyone can read', 'select', 'anon, authenticated', 'true')
        grant('anon', 'select'); grant('authenticated', 'select')
      } else if (ops.indexOf('select') >= 0 || ops.indexOf('update') >= 0) {
        // UPDATE needs a SELECT policy too, or it silently affects 0 rows.
        pol('owner reads', 'select', 'authenticated', mine)
        grant('authenticated', 'select')
      }
      if (ops.indexOf('insert') >= 0) { pol('owner inserts', 'insert', 'authenticated', null, mine); grant('authenticated', 'insert') }
      if (ops.indexOf('update') >= 0) { pol('owner updates', 'update', 'authenticated', mine, mine); grant('authenticated', 'update') }
      if (ops.indexOf('delete') >= 0) { pol('owner deletes', 'delete', 'authenticated', mine); grant('authenticated', 'delete') }
      if (o.ownerDefault !== false) {
        L.push('-- the client can omit ' + ownerCol + ' on insert')
        // a DEFAULT can't contain a subquery, so plain auth.uid() here
        L.push('alter table ' + t + ' alter column ' + ownerCol + ' set default auth.uid();')
        L.push('')
      }
      if (o.index !== false) {
        L.push('create index if not exists ' + table + '_' + ownerCol + '_idx on ' + t + ' (' + ownerCol + ');')
        L.push('')
      }
    }

    if (pattern === 'team') {
      var fn = 'private.' + table + '_my_' + teamCol + 's'
      var mt = schema + '.' + membersTable
      L.push('-- Membership lookup outside RLS, so policies never query ' + membersTable + ' through itself')
      L.push('-- (that raises 42P17 infinite recursion). Lives in a schema the API does not expose.')
      L.push('create schema if not exists private;')
      L.push('')
      L.push('create or replace function ' + fn + '()')
      L.push('returns setof ' + (o.teamColType || 'uuid'))
      L.push("language sql security definer set search_path = '' stable as $$")
      L.push('  select ' + membersTeamCol + ' from ' + mt)
      L.push('  where ' + membersUserCol + ' = ' + uid)
      L.push('$$;')
      L.push('')
      L.push('revoke all on function ' + fn + '() from public;')
      L.push('grant usage on schema private to authenticated;')
      L.push('grant execute on function ' + fn + '() to authenticated;')
      L.push('')
      var inTeam = teamCol + ' in (select ' + fn + '())'
      if (ops.indexOf('select') >= 0 || ops.indexOf('update') >= 0) { pol('members read', 'select', 'authenticated', inTeam); grant('authenticated', 'select') }
      if (ops.indexOf('insert') >= 0) { pol('members insert', 'insert', 'authenticated', null, inTeam); grant('authenticated', 'insert') }
      if (ops.indexOf('update') >= 0) { pol('members update', 'update', 'authenticated', inTeam, inTeam); grant('authenticated', 'update') }
      if (ops.indexOf('delete') >= 0) { pol('members delete', 'delete', 'authenticated', inTeam); grant('authenticated', 'delete') }
      if (o.index !== false) {
        L.push('create index if not exists ' + table + '_' + teamCol + '_idx on ' + t + ' (' + teamCol + ');')
        L.push('create index if not exists ' + membersTable + '_' + membersUserCol + '_idx on ' + mt + ' (' + membersUserCol + ');')
        L.push('')
      }
    }

    if (pattern === 'public_read_only') {
      pol('anyone can read', 'select', 'anon, authenticated', 'true')
      grant('anon', 'select'); grant('authenticated', 'select')
      L.push('-- No insert/update/delete policies: writes only from the server (service_role).')
      L.push('')
    }

    L.push('-- Grants: only what the API roles need (new tables get none by default).')
    ;['anon', 'authenticated'].forEach(function (role) {
      if (grants[role].length) {
        var list = OPS.filter(function (x) { return grants[role].indexOf(x) >= 0 })
        L.push('grant ' + list.join(', ') + ' on ' + t + ' to ' + role + ';')
      }
    })
    if (!grants.anon.length) L.push('-- no grant to anon: signed-out visitors can’t reach this table')

    var test = [
      '-- Check what the API roles can reach (run as postgres in the SQL editor)',
      'select c.relname, c.relrowsecurity as rls_on,',
      "       has_any_column_privilege('anon', c.oid, 'select') as anon_can_read,",
      "       has_any_column_privilege('authenticated', c.oid, 'select') as auth_can_read",
      'from pg_class c join pg_namespace n on n.oid = c.relnamespace',
      "where n.nspname = '" + schema + "' and c.relname = '" + table + "';",
    ].join('\n')

    return { sql: L.join('\n').replace(/\n{3,}/g, '\n\n').trim() + '\n', test: test, errors: [] }
  }

  // Owner / team columns we recognise, in priority order. First match wins.
  var OWNER_COLS = ['user_id', 'owner_id', 'owner', 'created_by', 'author_id', 'profile_id', 'account_id']
  var TEAM_COLS = ['team_id', 'workspace_id', 'org_id', 'organization_id', 'tenant_id', 'company_id', 'group_id']

  // Split a parenthesised column list on TOP-LEVEL commas (ignore commas inside
  // nested parens like numeric(10,2) or references ... (a, b)).
  function splitTopLevel(body) {
    var parts = [], depth = 0, cur = ''
    for (var i = 0; i < body.length; i++) {
      var c = body[i]
      if (c === '(') depth++
      else if (c === ')') depth--
      if (c === ',' && depth === 0) { parts.push(cur); cur = ''; continue }
      cur += c
    }
    if (cur.trim()) parts.push(cur)
    return parts
  }

  var CONSTRAINT_KW = /^(constraint|primary|foreign|unique|check|exclude|like|partition)\b/i

  /**
   * Parse a CREATE TABLE statement into { table, schema, columns, ownerCol,
   * teamCol, teamColType, suggestedPattern } or { error }. Best-effort and
   * regex-based (the authoritative parser is airlock's); it only needs to read
   * column names and types, so a dev can paste their real table and skip typing.
   */
  function parseCreateTable(sql) {
    var s = String(sql || '').replace(/--[^\n]*/g, ' ').replace(/\/\*[\s\S]*?\*\//g, ' ')
    var m = s.match(/create\s+table\s+(?:if\s+not\s+exists\s+)?("?[\w]+"?)(?:\s*\.\s*("?[\w]+"?))?\s*\(/i)
    if (!m) return { error: 'No CREATE TABLE found. Paste a statement like: create table public.notes ( id uuid primary key, user_id uuid, body text );' }
    var schema = m[2] ? m[1].replace(/"/g, '') : 'public'
    var table = (m[2] || m[1]).replace(/"/g, '')
    // The body is between the first '(' after the name and its matching ')'.
    var open = s.indexOf('(', m.index + m[0].length - 1)
    var depth = 0, end = -1
    for (var i = open; i < s.length; i++) {
      if (s[i] === '(') depth++
      else if (s[i] === ')') { depth--; if (depth === 0) { end = i; break } }
    }
    if (end < 0) return { error: 'Could not find the end of the column list — check the parentheses.' }
    var cols = []
    splitTopLevel(s.slice(open + 1, end)).forEach(function (raw) {
      var line = raw.trim()
      if (!line || CONSTRAINT_KW.test(line)) return
      var cm = line.match(/^"?([a-zA-Z_][\w]*)"?\s+(.+)$/)
      if (!cm) return
      var name = cm[1].toLowerCase()
      var type = cm[2].trim().split(/\s+/).slice(0, 2).join(' ').replace(/[,()].*$/, '').toLowerCase()
      cols.push({ name: name, type: type })
    })
    if (!cols.length) return { error: 'No columns found in the table.' }
    var names = cols.map(function (c) { return c.name })
    var ownerCol = OWNER_COLS.filter(function (c) { return names.indexOf(c) >= 0 })[0] || ''
    var teamCol = TEAM_COLS.filter(function (c) { return names.indexOf(c) >= 0 })[0] || ''
    var teamColType = 'uuid'
    if (teamCol) {
      var t = (cols.filter(function (c) { return c.name === teamCol })[0] || {}).type || ''
      teamColType = /int|serial|bigint/.test(t) ? (/\bbig/.test(t) ? 'bigint' : 'integer') : 'uuid'
    }
    var suggestedPattern = teamCol ? 'team' : (ownerCol ? 'owner' : 'public_read_only')
    return {
      table: table, schema: schema, columns: cols,
      ownerCol: ownerCol || 'user_id', teamCol: teamCol || 'team_id',
      teamColType: teamColType, suggestedPattern: suggestedPattern,
      detectedOwner: !!ownerCol, detectedTeam: !!teamCol,
    }
  }

  // Explain a policy in plain English + flag if it leaks. Client-side, best-effort.
  // Reads one `create policy ...` statement; the authoritative engine is airlock's.
  function isAlwaysTrue(expr) {
    var e = String(expr || '').trim().replace(/\s+/g, ' ')
    if (!e) return false
    if (/^\(?\s*true\s*\)?$/i.test(e)) return true
    if (/\b(\w+)\s*=\s*\1\b/i.test(e)) return true
    if (/\b(\d+)\s*=\s*\1\b/.test(e)) return true
    if (/'([^']*)'\s*=\s*'\1'/.test(e)) return true
    return false
  }
  function hasUid(expr) { return /auth\.uid\(\)/i.test(String(expr || '')) }

  function grabParen(s, kwIndex) {
    var open = s.indexOf('(', kwIndex)
    if (open < 0) return null
    var depth = 0
    for (var i = open; i < s.length; i++) {
      if (s[i] === '(') depth++
      else if (s[i] === ')') { depth--; if (depth === 0) return s.slice(open + 1, i).trim() }
    }
    return null
  }

  function explainPolicy(sql) {
    var s = String(sql || '').replace(/--[^\n]*/g, ' ').replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/\s+/g, ' ').trim()
    var m = s.match(/create\s+policy\s+("([^"]+)"|[a-z_][\w]*)\s+on\s+(?:([a-z_][\w]*)\s*\.\s*)?([a-z_][\w]*)/i)
    if (!m) return { error: 'No CREATE POLICY found. Paste a statement like: create policy "owner reads" on notes for select to authenticated using (user_id = auth.uid());' }
    var name = (m[2] || m[1]).replace(/"/g, '')
    var table = m[4]
    var restrictive = /\bas\s+restrictive\b/i.test(s)
    var cmdM = s.match(/\bfor\s+(all|select|insert|update|delete)\b/i)
    var cmd = cmdM ? cmdM[1].toLowerCase() : 'all'
    var toM = s.match(/\bto\s+([a-z_][\w, ]*?)\s*(?:\busing\b|\bwith\s+check\b|;|$)/i)
    var roles = toM ? toM[1].split(',').map(function (r) { return r.trim().toLowerCase() }).filter(Boolean) : ['(every role)']
    var uIdx = s.search(/\busing\s*\(/i)
    var cIdx = s.search(/\bwith\s+check\s*\(/i)
    var using = uIdx >= 0 ? grabParen(s, uIdx) : null
    var withCheck = cIdx >= 0 ? grabParen(s, cIdx) : null

    var clientRoles = roles.some(function (r) { return r === 'anon' || r === 'authenticated' || r === 'public' || r === '(every role)' })
    var anon = roles.some(function (r) { return r === 'anon' || r === 'public' || r === '(every role)' })
    var who = roles.join(', ')
    var findings = [], lines = []
    var reads = cmd === 'select' || cmd === 'all'
    var writesNew = cmd === 'insert' || cmd === 'update' || cmd === 'all'

    lines.push('Applies to ' + (restrictive ? 'RESTRICTIVE ' : '') + cmd.toUpperCase() + ' for: ' + who + '.')

    if (uIdx >= 0 || cmd === 'insert') {
      if (cmd === 'insert') {
        lines.push('INSERT has no USING clause — only WITH CHECK applies.')
      } else if (using === null) {
        lines.push('USING is empty or unreadable.')
      } else if (isAlwaysTrue(using)) {
        lines.push('USING is always true: every row matches.')
        if (clientRoles) findings.push({ sev: 'leak', msg: 'Always-true USING for a client role (' + who + '): every row is ' + (reads ? 'readable' : 'reachable') + '. This is the classic RLS leak.' })
      } else if (hasUid(using)) {
        lines.push('USING scopes rows to the signed-in user (uses auth.uid()).')
      } else {
        lines.push('USING = ' + using + ' — it filters rows, but not by auth.uid(); confirm it restricts the caller.')
        if (anon && reads) findings.push({ sev: 'review', msg: 'anon can read whatever this USING allows, with no per-user scope. If the rows are not meant to be public, scope to auth.uid().' })
      }
    }
    if (writesNew) {
      if (withCheck === null) {
        if (cmd === 'insert') {
          // Postgres: an INSERT policy without WITH CHECK admits no rows (USING isn't allowed on INSERT).
          lines.push('No WITH CHECK: an INSERT policy without one lets no rows in.')
          if (clientRoles) findings.push({ sev: 'review', msg: 'INSERT policy without WITH CHECK for ' + who + ' lets no rows in. If inserts should work, add with check (user_id = (select auth.uid())).' })
        } else {
          // Postgres reuses USING for the new row. Only a wide USING (an OR) lets a row be changed into one the caller doesn't own.
          lines.push('No WITH CHECK: Postgres checks the new row against USING too.')
          if (clientRoles && using && !isAlwaysTrue(using) && /\bor\b/i.test(using)) findings.push({ sev: 'review', msg: 'No WITH CHECK, and USING has an OR: a row can be changed into any row that still matches USING (e.g. a shared row handed to another user). Add a strict WITH CHECK.' })
        }
      } else if (isAlwaysTrue(withCheck)) {
        lines.push('WITH CHECK is always true: any new row is accepted.')
        if (clientRoles) findings.push({ sev: 'leak', msg: 'Always-true WITH CHECK for ' + who + ': a client can write rows as anyone.' })
      } else if (hasUid(withCheck)) {
        lines.push('WITH CHECK ties the new row to the signed-in user (uses auth.uid()).')
      } else {
        lines.push('WITH CHECK = ' + withCheck + ' — constrains the new row, but not by auth.uid().')
      }
    }
    if (cmd === 'update' && using !== null && !isAlwaysTrue(using) && !hasUid(using) && clientRoles) {
      findings.push({ sev: 'review', msg: 'UPDATE USING is not scoped to auth.uid(): any row this role can see can be targeted for update.' })
    }

    var verdict = findings.some(function (f) { return f.sev === 'leak' }) ? 'leak'
      : findings.some(function (f) { return f.sev === 'review' }) ? 'review' : 'ok'
    return { name: name, table: table, cmd: cmd, roles: roles, restrictive: restrictive, using: using, withCheck: withCheck, lines: lines, findings: findings, verdict: verdict }
  }

  var api = { generate: generate, parseCreateTable: parseCreateTable, explainPolicy: explainPolicy, PATTERNS: PATTERNS, OPS: OPS }
  if (typeof module === 'object' && module.exports) module.exports = api
  else root.RLSGen = api
})(this)
