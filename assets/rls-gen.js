/* Supabase RLS policy generator — pure logic, no DOM.
 * Used by /supabase-rls-policy-generator/ and by the tests that run every
 * generated migration against Postgres as anon / authenticated users.
 * Exposes RLSGen.generate(opts) -> { sql, test, errors }.
 */
(function (root) {
  'use strict'

  var IDENT = /^[a-z_][a-z0-9_]{0,62}$/
  var OPS = ['select', 'insert', 'update', 'delete']

  var PATTERNS = {
    owner: 'Private: each user sees and changes only their own rows',
    owner_public_read: 'Public read, owner writes (profiles, posts, listings)',
    team: 'Team / workspace: members see and change their team’s rows',
    public_read_only: 'Public read-only (catalog, pricing): no writes from the API',
  }

  function q(name) { return name } // identifiers are validated, never quoted

  function generate(o) {
    o = o || {}
    var errors = []
    var schema = o.schema || 'public'
    var table = o.table || ''
    var pattern = o.pattern || 'owner'
    var ownerCol = o.ownerCol || 'user_id'
    var teamCol = o.teamCol || 'team_id'
    var membersTable = o.membersTable || 'team_members'
    var membersUserCol = o.membersUserCol || 'user_id'
    var membersTeamCol = o.membersTeamCol || 'team_id'
    var ops = (o.ops && o.ops.length ? o.ops : OPS).filter(function (x) { return OPS.indexOf(x) >= 0 })

    var check = { schema: schema, table: table }
    if (pattern === 'owner' || pattern === 'owner_public_read') check.ownerCol = ownerCol
    if (pattern === 'team') {
      check.teamCol = teamCol; check.membersTable = membersTable
      check.membersUserCol = membersUserCol; check.membersTeamCol = membersTeamCol
    }
    Object.keys(check).forEach(function (k) {
      if (!IDENT.test(check[k])) errors.push(k + ': use lowercase letters, digits and _ (start with a letter or _)')
    })
    if (!PATTERNS[pattern]) errors.push('pattern: unknown')
    if (schema === 'auth' || schema === 'storage' || schema === 'private') errors.push('schema: pick the schema your API exposes (usually public)')
    if (errors.length) return { sql: '', test: '', errors: errors }

    var t = schema + '.' + table
    var uid = '(select auth.uid())'
    var L = []
    var grants = { anon: [], authenticated: [] }
    function pol(name, op, role, using, withCheck) {
      var s = 'create policy "' + name + '" on ' + t + '\n  for ' + op + ' to ' + role
      if (using) s += '\n  using (' + using + ')'
      if (withCheck) s += '\n  with check (' + withCheck + ')'
      L.push(s + ';')
      L.push('')
    }
    function grant(role, op) { if (grants[role].indexOf(op) < 0) grants[role].push(op) }

    L.push('-- RLS for ' + t + ' · ' + PATTERNS[pattern])
    L.push('-- Generated by https://shipsealed.com/supabase-rls-policy-generator/')
    L.push('-- Run in the same migration that creates the table.')
    L.push('')
    L.push('alter table ' + t + ' enable row level security;')
    L.push('')

    if (pattern === 'owner' || pattern === 'owner_public_read') {
      var mine = ownerCol + ' = ' + uid
      if (pattern === 'owner_public_read') {
        pol('anyone can read', 'select', 'anon, authenticated', 'true')
        grant('anon', 'select'); grant('authenticated', 'select')
      } else if (ops.indexOf('select') >= 0 || ops.indexOf('update') >= 0) {
        // UPDATE needs a SELECT policy too, or it silently affects 0 rows.
        pol('owner reads', 'select', 'authenticated', mine)
        grant('authenticated', 'select')
      }
      if (ops.indexOf('insert') >= 0) { pol('owner inserts', 'insert', 'authenticated', null, mine); grant('authenticated', 'insert') }
      if (ops.indexOf('update') >= 0) { pol('owner updates', 'update', 'authenticated', mine, mine); grant('authenticated', 'update') }
      if (ops.indexOf('delete') >= 0) { pol('owner deletes', 'delete', 'authenticated', mine); grant('authenticated', 'delete') }
      if (o.ownerDefault !== false) {
        L.push('-- the client can omit ' + ownerCol + ' on insert')
        // a DEFAULT can't contain a subquery, so plain auth.uid() here
        L.push('alter table ' + t + ' alter column ' + ownerCol + ' set default auth.uid();')
        L.push('')
      }
      if (o.index !== false) {
        L.push('create index if not exists ' + table + '_' + ownerCol + '_idx on ' + t + ' (' + ownerCol + ');')
        L.push('')
      }
    }

    if (pattern === 'team') {
      var fn = 'private.' + table + '_my_' + teamCol + 's'
      var mt = schema + '.' + membersTable
      L.push('-- Membership lookup outside RLS, so policies never query ' + membersTable + ' through itself')
      L.push('-- (that raises 42P17 infinite recursion). Lives in a schema the API does not expose.')
      L.push('create schema if not exists private;')
      L.push('')
      L.push('create or replace function ' + fn + '()')
      L.push('returns setof ' + (o.teamColType || 'uuid'))
      L.push("language sql security definer set search_path = '' stable as $$")
      L.push('  select ' + membersTeamCol + ' from ' + mt)
      L.push('  where ' + membersUserCol + ' = ' + uid)
      L.push('$$;')
      L.push('')
      L.push('revoke all on function ' + fn + '() from public;')
      L.push('grant usage on schema private to authenticated;')
      L.push('grant execute on function ' + fn + '() to authenticated;')
      L.push('')
      var inTeam = teamCol + ' in (select ' + fn + '())'
      if (ops.indexOf('select') >= 0 || ops.indexOf('update') >= 0) { pol('members read', 'select', 'authenticated', inTeam); grant('authenticated', 'select') }
      if (ops.indexOf('insert') >= 0) { pol('members insert', 'insert', 'authenticated', null, inTeam); grant('authenticated', 'insert') }
      if (ops.indexOf('update') >= 0) { pol('members update', 'update', 'authenticated', inTeam, inTeam); grant('authenticated', 'update') }
      if (ops.indexOf('delete') >= 0) { pol('members delete', 'delete', 'authenticated', inTeam); grant('authenticated', 'delete') }
      if (o.index !== false) {
        L.push('create index if not exists ' + table + '_' + teamCol + '_idx on ' + t + ' (' + teamCol + ');')
        L.push('create index if not exists ' + membersTable + '_' + membersUserCol + '_idx on ' + mt + ' (' + membersUserCol + ');')
        L.push('')
      }
    }

    if (pattern === 'public_read_only') {
      pol('anyone can read', 'select', 'anon, authenticated', 'true')
      grant('anon', 'select'); grant('authenticated', 'select')
      L.push('-- No insert/update/delete policies: writes only from the server (service_role).')
      L.push('')
    }

    L.push('-- Grants: only what the API roles need (new tables get none by default).')
    ;['anon', 'authenticated'].forEach(function (role) {
      if (grants[role].length) {
        var list = OPS.filter(function (x) { return grants[role].indexOf(x) >= 0 })
        L.push('grant ' + list.join(', ') + ' on ' + t + ' to ' + role + ';')
      }
    })
    if (!grants.anon.length) L.push('-- no grant to anon: signed-out visitors can’t reach this table')

    var test = [
      '-- Check what the API roles can reach (run as postgres in the SQL editor)',
      'select c.relname, c.relrowsecurity as rls_on,',
      "       has_table_privilege('anon', c.oid, 'select') as anon_can_read,",
      "       has_table_privilege('authenticated', c.oid, 'select') as auth_can_read",
      'from pg_class c join pg_namespace n on n.oid = c.relnamespace',
      "where n.nspname = '" + schema + "' and c.relname = '" + table + "';",
    ].join('\n')

    return { sql: L.join('\n').replace(/\n{3,}/g, '\n\n').trim() + '\n', test: test, errors: [] }
  }

  var api = { generate: generate, PATTERNS: PATTERNS, OPS: OPS }
  if (typeof module === 'object' && module.exports) module.exports = api
  else root.RLSGen = api
})(this)
